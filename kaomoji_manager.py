async def detect_emotion(text: str) -> str:
    """从用户消息中检测情绪"""
    text_lower = text.lower()

    # 统计每个情绪的匹配分数
    scores = {}
    for emotion, keywords in KEYWORD_DETECT.items():
        score = sum(1 for kw in keywords if kw in text_lower)
        if score > 0:
            scores[emotion] = score

    if scores:
        return max(scores, key=scores.get)

    return "greeting"


async def get_kaomoji(emotion: str) -> str:
    """获取颜文字"""
    kaomojis = KAOMOJI.get(emotion, KAOMOJI["greeting"])
    return random.choice(kaomojis)


async def add_kaomoji_to_reply(reply: str, emotion: str) -> str:
    """在回复中添加颜文字"""
    kaomoji = await get_kaomoji(emotion)

    # 随机决定颜文字放在前面还是后面
    if random.random() < 0.5:
        return f"{kaomoji} {reply}"
    else:
        return f"{reply} {kaomoji}"


